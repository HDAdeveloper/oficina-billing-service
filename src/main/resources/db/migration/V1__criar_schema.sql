-- Billing Service: banco próprio, nenhum outro serviço acessa estas tabelas.

CREATE TABLE orcamento (
    id                  VARCHAR(36)    PRIMARY KEY,
    versao              BIGINT         NOT NULL DEFAULT 0,
    os_id               BIGINT         NOT NULL,
    cliente_id          BIGINT,
    email_cliente       VARCHAR(150),
    status              VARCHAR(20)    NOT NULL,
    motivo_cancelamento VARCHAR(500),
    valor_total         NUMERIC(12, 2) NOT NULL,
    criado_em           TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_orcamento_os ON orcamento (os_id);
-- No máximo um orçamento ativo (pendente ou pago) por OS, mesmo com dois pedidos simultâneos
CREATE UNIQUE INDEX uk_orcamento_ativo_por_os ON orcamento (os_id) WHERE status IN ('PENDENTE', 'PAGO');

CREATE TABLE orcamento_item (
    orcamento_id   VARCHAR(36)    NOT NULL REFERENCES orcamento (id) ON DELETE CASCADE,
    ordem          INTEGER        NOT NULL,
    tipo           VARCHAR(10)    NOT NULL,
    codigo         VARCHAR(40)    NOT NULL,
    descricao      VARCHAR(255)   NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (orcamento_id, ordem)
);

CREATE TABLE pagamento (
    id            VARCHAR(36)    PRIMARY KEY,
    versao        BIGINT         NOT NULL DEFAULT 0,
    orcamento_id  VARCHAR(36)    NOT NULL REFERENCES orcamento (id),
    os_id         BIGINT         NOT NULL,
    valor         NUMERIC(12, 2) NOT NULL,
    metodo        VARCHAR(40),
    status        VARCHAR(20)    NOT NULL,
    id_externo    VARCHAR(100),
    motivo        VARCHAR(500),
    criado_em     TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_pagamento_orcamento ON pagamento (orcamento_id);
-- Trava contra cobrança dupla: só um pagamento aprovado por orçamento
CREATE UNIQUE INDEX uk_pagamento_aprovado_por_orcamento ON pagamento (orcamento_id) WHERE status = 'APROVADO';

-- Mensagens já tratadas (idempotência da entrega at-least-once)
CREATE TABLE mensagem_processada (
    message_id    VARCHAR(64) PRIMARY KEY,
    processada_em TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Outbox: eventos gravados na mesma transação do estado e enviados ao SNS por um publicador
CREATE TABLE outbox_evento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id     VARCHAR(36)   NOT NULL,
    tipo           VARCHAR(60)   NOT NULL,
    os_id          BIGINT,
    saga_id        VARCHAR(64),
    correlation_id VARCHAR(100),
    payload        VARCHAR(4000) NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    publicado_em   TIMESTAMP WITH TIME ZONE,
    tentativas     INTEGER       NOT NULL DEFAULT 0,
    ultimo_erro    VARCHAR(500),
    CONSTRAINT uk_outbox_message UNIQUE (message_id)
);
CREATE INDEX idx_outbox_pendentes ON outbox_evento (id) WHERE publicado_em IS NULL;
